const { contextBridge, ipcRenderer } = require('electron');
const request = async (channel, arg) => {
  const result = await ipcRenderer.invoke(channel, arg);
  if (!result.ok) throw new Error(result.error);
  return result.value;
};
contextBridge.exposeInMainWorld('querydesk', {
  snippets: () => request('snippets:list'),
  saveSnippet: value => request('snippets:save', value),
  removeSnippet: id => request('snippets:remove', id),
  updateStatus: () => request('updates:status'),
  openGitUpdateGuide: () => request('updates:open-git-guide'),
  checkUpdates: () => request('updates:check'),
  downloadUpdate: () => request('updates:download'),
  cancelUpdate: () => request('updates:cancel'),
  revealUpdate: () => request('updates:reveal'),
  installUpdate: () => request('updates:install'),
  profiles: () => request('profiles:list'),
  saveProfile: value => request('profiles:save', value),
  removeProfile: id => request('profiles:remove', id),
  connect: value => request('db:connect', value),
  disconnect: () => request('db:disconnect'),
  cancelQuery: () => request('db:cancel'),
  schemas: () => request('db:schemas'),
  columns: value => request('db:columns', value),
  tableData: value => request('db:tableData', value),
  previewChanges: value => request('db:previewChanges', value),
  applyChanges: value => request('db:applyChanges', value),
  transferInfo: value => request('db:transferInfo', value),
  pickTransfer: value => request('transfer:pick', value),
  inspectImport: value => request('transfer:inspect', value),
  exportDatabase: value => request('transfer:export', value),
  importDatabase: value => request('transfer:import', value),
  query: value => request('db:query', value),
  script: value => request('db:script', value),
  info: () => request('db:info'),
  testConnection: value => request('db:testConnection', value),
  sshFingerprint: value => request('ssh:fingerprint', value),
  pickSshKey: () => request('ssh:pickKey'),
  history: value => request('history:list', value),
  historyUpdate: value => request('history:update', value),
  historyRemove: id => request('history:remove', id),
  historyClear: () => request('history:clear'),
  historySettings: value => request('history:settings', value),
  copyText: value => request('clipboard:write', value),
  openFile: () => request('file:open'),
  saveFile: value => request('file:save', value),
  exportCsv: value => request('file:export', value),
  pickLocalDatabase: value => request('local:pick', value),
  formatSql: value => request('sql:format', value),
  onAction: listener => { const callback = (_event, action) => listener(action); ipcRenderer.on('app:action', callback); return () => ipcRenderer.removeListener('app:action', callback); },
});
