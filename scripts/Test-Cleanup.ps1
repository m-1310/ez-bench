$ErrorActionPreference = 'Stop'
$projectRoot = [IO.Path]::GetFullPath((Split-Path -Parent $PSScriptRoot))
$allowedRoot = [IO.Path]::GetFullPath((Join-Path $projectRoot 'target')) + [IO.Path]::DirectorySeparatorChar
$fixtureRoot = [IO.Path]::GetFullPath((Join-Path $projectRoot ('target\cleanup-test-' + [guid]::NewGuid().ToString('N'))))
if (!$fixtureRoot.StartsWith($allowedRoot,[StringComparison]::OrdinalIgnoreCase)) { throw 'Cleanup test escaped target/.' }
function Write-Fixture([string] $Relative, [string] $Text) {
    $file = Join-Path $fixtureRoot $Relative
    New-Item -ItemType Directory -Path (Split-Path -Parent $file) -Force | Out-Null
    $Text | Set-Content -LiteralPath $file -Encoding utf8
}
try {
    Write-Fixture 'app\package.json' '{"name":"ez-bench","version":"0.8.0"}'
    Write-Fixture 'build\EZ Bench 0.6.0-final\EZ Bench.exe' 'current test placeholder; never executed'
    Write-Fixture 'build\EZ Bench 0.8.0-candidate\EZ Bench.exe' 'latest test placeholder; never executed'
    Write-Fixture 'build\EZ Bench 0.5.0\obsolete.txt' 'old generated bytes'
    Write-Fixture 'build\EZ Bench 0.4.0\database.db' 'possible user data; must survive'
    Write-Fixture 'build\unrelated\keep.txt' 'unrelated directory'
    Write-Fixture 'releases\EZ-Bench-0.5.0-win-x64.zip' 'obsolete test archive'
    Write-Fixture 'releases\0.6.0\keep.zip' 'current archive'
    Write-Fixture 'releases\0.8.0\keep.zip' 'latest archive'
    Write-Fixture 'target\integration-tools\database.db' 'fixture database; must survive'
    $pointer = @{version='0.6.0';executable=(Join-Path $fixtureRoot 'build\EZ Bench 0.6.0-final\EZ Bench.exe')}
    Write-Fixture 'build\current.json' ($pointer | ConvertTo-Json)
    $preview = & (Join-Path $PSScriptRoot 'Clean-Artifacts.ps1') -RootDirectory $fixtureRoot | ConvertFrom-Json
    if ($preview.candidateCount -ne 2 -or !(Test-Path -LiteralPath (Join-Path $fixtureRoot 'build\EZ Bench 0.5.0'))) { throw 'Cleanup preview changed files or selected unexpected paths.' }
    $applied = & (Join-Path $PSScriptRoot 'Clean-Artifacts.ps1') -RootDirectory $fixtureRoot -Apply | ConvertFrom-Json
    if ($applied.removedCount -ne 2 -or (Test-Path -LiteralPath (Join-Path $fixtureRoot 'build\EZ Bench 0.5.0'))) { throw 'Cleanup did not remove only obsolete generated artifacts.' }
    foreach ($relative in @('build\EZ Bench 0.6.0-final\EZ Bench.exe','build\EZ Bench 0.8.0-candidate\EZ Bench.exe','build\EZ Bench 0.4.0\database.db','build\unrelated\keep.txt','target\integration-tools\database.db','releases\0.6.0\keep.zip','releases\0.8.0\keep.zip')) {
        if (!(Test-Path -LiteralPath (Join-Path $fixtureRoot $relative))) { throw ('Protected test file was removed: ' + $relative) }
    }
    $again = & (Join-Path $PSScriptRoot 'Clean-Artifacts.ps1') -RootDirectory $fixtureRoot | ConvertFrom-Json
    if ($again.candidateCount -ne 0) { throw 'Cleanup should be idempotent.' }
    Write-Fixture 'app\node_modules\ssh2\test\fixtures\id_rsa.ppk' 'known public dependency fixture bytes'
    Write-Fixture 'build\EZ Bench 0.3.0\resources\app\node_modules\ssh2\test\fixtures\id_rsa.ppk' 'known public dependency fixture bytes'
    Write-Fixture 'build\EZ Bench 0.2.0\custom.ppk' 'private user file; must survive'
    $fixtures = & (Join-Path $PSScriptRoot 'Clean-Artifacts.ps1') -RootDirectory $fixtureRoot -Apply | ConvertFrom-Json
    if ($fixtures.removedCount -ne 1 -or !(Test-Path -LiteralPath (Join-Path $fixtureRoot 'build\EZ Bench 0.2.0\custom.ppk'))) { throw 'Dependency fixture exemption did not preserve unrelated private keys.' }
    Write-Fixture 'build\current.json' '{"version":"bad"}'
    $failed = $false
    try { & (Join-Path $PSScriptRoot 'Clean-Artifacts.ps1') -RootDirectory $fixtureRoot -Apply | Out-Null } catch { $failed = $true }
    if (!$failed) { throw 'Cleanup did not stop on an invalid current pointer.' }
    'Cleanup safety tests passed: preview, deletion scope, fallback/latest preservation, data preservation and invalid-pointer refusal.'
} finally {
    $resolved = [IO.Path]::GetFullPath($fixtureRoot)
    if (!$resolved.StartsWith($allowedRoot,[StringComparison]::OrdinalIgnoreCase) -or !(Split-Path -Leaf $resolved).StartsWith('cleanup-test-')) { throw 'Unexpected cleanup test removal path.' }
    if (Test-Path -LiteralPath $resolved) { Remove-Item -LiteralPath $resolved -Recurse -Force }
}
